#!/usr/bin/env node
'use strict';

const http = require('node:http');
const fs = require('node:fs');
const fsp = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const crypto = require('node:crypto');

const APP_ROOT = path.resolve(__dirname, '..');
const DATA_DIR = process.env.HSW_DATA_DIR || path.join(os.homedir(), '.harness-switch');
const HOST = process.env.HOST || '127.0.0.1';
const PORT = Number(process.env.PORT || 8787);
const SESSION_TTL_MS = 24 * 60 * 60 * 1000;
const sessions = new Map();
const files = {
  profiles: path.join(DATA_DIR, 'profiles.json'),
  active: path.join(DATA_DIR, 'active.json'),
  password: path.join(DATA_DIR, 'web_password'),
  key: path.join(DATA_DIR, 'aes-256-gcm.key'),
  env: path.join(DATA_DIR, 'env.sh'),
};

const harnesses = {
  claude: { label: 'Claude Code' },
  pi: { label: 'pi' },
  codex: { label: 'Codex' },
  zcode: { label: 'zcode' },
  kimi: { label: 'Kimi Code' },
};

function ensureDir() { fs.mkdirSync(DATA_DIR, { recursive: true, mode: 0o700 }); }
function secureWrite(file, text) {
  const tmp = `${file}.${process.pid}.${crypto.randomBytes(4).toString('hex')}.tmp`;
  fs.writeFileSync(tmp, text, { encoding: 'utf8', mode: 0o600 });
  fs.renameSync(tmp, file);
  try { fs.chmodSync(file, 0o600); } catch { /* Windows has no POSIX file permissions */ }
}
function readJson(file, fallback = {}) { try { return JSON.parse(fs.readFileSync(file, 'utf8')); } catch { return fallback; } }
function writeJson(file, object) { secureWrite(file, `${JSON.stringify(object, null, 2)}\n`); }
function initSecret(file, bytes) {
  if (!fs.existsSync(file)) secureWrite(file, crypto.randomBytes(bytes).toString('base64url') + '\n');
  return Buffer.from(fs.readFileSync(file, 'utf8').trim(), 'base64url');
}
function getPassword() {
  if (!fs.existsSync(files.password)) {
    const password = crypto.randomBytes(18).toString('base64url');
    secureWrite(files.password, `${password}\n`);
    console.log(`[harness-switch] Initial web password: ${password}`);
  }
  return fs.readFileSync(files.password, 'utf8').trim();
}
function encrypt(plain) {
  const key = initSecret(files.key, 32);
  const iv = crypto.randomBytes(12);
  const cipher = crypto.createCipheriv('aes-256-gcm', key, iv);
  const ciphertext = Buffer.concat([cipher.update(plain, 'utf8'), cipher.final()]);
  return { iv: iv.toString('base64url'), tag: cipher.getAuthTag().toString('base64url'), data: ciphertext.toString('base64url') };
}
function decrypt(value) {
  try {
    const key = initSecret(files.key, 32);
    const decipher = crypto.createDecipheriv('aes-256-gcm', key, Buffer.from(value.iv, 'base64url'));
    decipher.setAuthTag(Buffer.from(value.tag, 'base64url'));
    return Buffer.concat([decipher.update(Buffer.from(value.data, 'base64url')), decipher.final()]).toString('utf8');
  } catch { return ''; }
}
function escapeToml(value) { return String(value || '').replace(/\\/g, '\\\\').replace(/"/g, '\\"'); }
function shellQuote(value) { return `'${String(value || '').replace(/'/g, `'"'"'`)}'`; }
function activeForResponse(active) {
  return Object.fromEntries(Object.entries(active).map(([h, p]) => [h, { name: p.name, base_url: p.base_url, model: p.model || '' }]));
}
function profileForResponse(harness, name, profile) {
  return { harness, name, base_url: profile.base_url || '', model: profile.model || '', notes: profile.notes || '', updated_at: profile.updated_at || '' };
}
function writeEnv(active) {
  const map = {
    claude: { ANTHROPIC_BASE_URL: 'base_url', ANTHROPIC_API_KEY: 'api_key', ANTHROPIC_MODEL: 'model' },
    codex: { OPENAI_BASE_URL: 'base_url', OPENAI_API_KEY: 'api_key', CODEX_MODEL: 'model' },
    pi: { PI_API_BASE: 'base_url', PI_API_KEY: 'api_key', PI_MODEL: 'model' },
    zcode: { ZCODE_BASE_URL: 'base_url', ZCODE_API_KEY: 'api_key', ZCODE_MODEL: 'model' },
    kimi: { KIMI_BASE_URL: 'base_url', KIMI_API_KEY: 'api_key', KIMI_MODEL: 'model' },
  };
  const lines = ['# Generated by harness-switch. Source this file in the shell where you launch your harness.', '# This file contains secrets. Do not commit it.'];
  for (const [harness, profile] of Object.entries(active)) {
    lines.push(`# ${harnesses[harness].label} / ${profile.name}`);
    for (const [env, field] of Object.entries(map[harness])) if (profile[field]) lines.push(`export ${env}=${shellQuote(profile[field])}`);
  }
  secureWrite(files.env, `${lines.join('\n')}\n`);
}
function writeNativeConfig(harness, profile) {
  const home = os.homedir();
  if (harness === 'claude') {
    const target = path.join(home, '.claude', 'settings.json');
    fs.mkdirSync(path.dirname(target), { recursive: true, mode: 0o700 });
    const current = readJson(target, {});
    current.env = { ...(current.env || {}), ANTHROPIC_BASE_URL: profile.base_url, ANTHROPIC_API_KEY: profile.api_key };
    if (profile.model) current.env.ANTHROPIC_MODEL = profile.model;
    secureWrite(target, `${JSON.stringify(current, null, 2)}\n`);
  }
  if (harness === 'kimi') {
    const target = path.join(home, '.kimi', 'config.toml');
    const model = profile.model || 'kimi-for-coding';
    fs.mkdirSync(path.dirname(target), { recursive: true, mode: 0o700 });
    const content = `default_model = "${escapeToml(model)}"\n\n[providers.harness_switch]\ntype = "kimi"\nbase_url = "${escapeToml(profile.base_url)}"\napi_key = "${escapeToml(profile.api_key)}"\n\n[models.harness_switch_model]\nprovider = "harness_switch"\nmodel = "${escapeToml(model)}"\nmax_context_size = 262144\n`;
    secureWrite(target, content);
  }
}
function send(res, code, body, headers = {}) { res.writeHead(code, headers); res.end(body); }
function json(res, code, data) { send(res, code, JSON.stringify(data), { 'Content-Type': 'application/json; charset=utf-8', 'Cache-Control': 'no-store', 'X-Content-Type-Options': 'nosniff' }); }
function parseCookies(req) { return Object.fromEntries((req.headers.cookie || '').split(';').map(x => x.trim()).filter(Boolean).map(x => { const i = x.indexOf('='); return [x.slice(0, i), decodeURIComponent(x.slice(i + 1))]; })); }
function isAuthed(req) { const t = parseCookies(req).hsw_session; const entry = t && sessions.get(t); if (!entry || entry.expires < Date.now()) { if (t) sessions.delete(t); return false; } return true; }
function requireAuth(req, res) { if (isAuthed(req)) return true; if (req.url.startsWith('/api/')) json(res, 401, { error: 'authentication required' }); else send(res, 303, '', { Location: '/login' }); return false; }
function body(req) { return new Promise((resolve, reject) => { let raw = ''; req.on('data', c => { raw += c; if (raw.length > 1024 * 1024) req.destroy(); }); req.on('end', () => resolve(raw)); req.on('error', reject); }); }
function contentType(file) { return file.endsWith('.css') ? 'text/css; charset=utf-8' : file.endsWith('.js') ? 'text/javascript; charset=utf-8' : 'text/html; charset=utf-8'; }
function sendStatic(res, relative) {
  const target = path.resolve(APP_ROOT, 'public', relative);
  if (!target.startsWith(path.resolve(APP_ROOT, 'public') + path.sep) || !fs.existsSync(target)) return send(res, 404, 'Not found');
  send(res, 200, fs.readFileSync(target), { 'Content-Type': contentType(target), 'X-Content-Type-Options': 'nosniff' });
}
function loginPage() { return `<!doctype html><html lang="zh-CN"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>harness-switch 登录</title><link rel="stylesheet" href="/static/style.css"></head><body class="auth"><form class="card auth-card" method="post" action="/login"><div class="eyebrow">HARNESS SWITCH</div><h1>服务器端配置中枢</h1><p class="muted">输入首次启动时终端打印的 Web 密码。</p><label>Web 密码<input type="password" name="password" autofocus required></label><button>登录</button></form></body></html>`; }

ensureDir();
const server = http.createServer(async (req, res) => {
  const url = new URL(req.url, `http://${req.headers.host || 'localhost'}`);
  try {
    if (req.method === 'GET' && url.pathname === '/healthz') return json(res, 200, { ok: true });
    if (req.method === 'GET' && url.pathname === '/login') return send(res, 200, loginPage(), { 'Content-Type': 'text/html; charset=utf-8' });
    if (req.method === 'POST' && url.pathname === '/login') {
      const form = new URLSearchParams(await body(req));
      const provided = form.get('password') || '';
      const expected = getPassword();
      const match = Buffer.byteLength(provided) === Buffer.byteLength(expected) && crypto.timingSafeEqual(Buffer.from(provided), Buffer.from(expected));
      if (!match) return send(res, 303, '', { Location: '/login' });
      const token = crypto.randomBytes(32).toString('base64url'); sessions.set(token, { expires: Date.now() + SESSION_TTL_MS });
      return send(res, 303, '', { Location: '/', 'Set-Cookie': `hsw_session=${token}; HttpOnly; SameSite=Lax; Path=/; Max-Age=${SESSION_TTL_MS / 1000}` });
    }
    if (req.method === 'POST' && url.pathname === '/logout') { const t = parseCookies(req).hsw_session; if (t) sessions.delete(t); return send(res, 303, '', { Location: '/login', 'Set-Cookie': 'hsw_session=; HttpOnly; SameSite=Lax; Path=/; Max-Age=0' }); }
    if (url.pathname.startsWith('/static/')) return sendStatic(res, url.pathname.slice('/static/'.length));
    if (req.method === 'GET' && url.pathname === '/') { if (!requireAuth(req, res)) return; return sendStatic(res, 'index.html'); }
    if (url.pathname.startsWith('/api/')) {
      if (!requireAuth(req, res)) return;
      if (req.method !== 'GET' && req.headers.origin && req.headers.origin !== `http://${req.headers.host}` && req.headers.origin !== `https://${req.headers.host}`) return json(res, 403, { error: 'cross-origin request denied' });
      if (req.method === 'GET' && url.pathname === '/api/state') {
        const profiles = readJson(files.profiles, {}), active = readJson(files.active, {}), result = Object.fromEntries(Object.keys(harnesses).map(h => [h, []]));
        for (const [h, entries] of Object.entries(profiles)) for (const [name, p] of Object.entries(entries || {})) if (harnesses[h]) result[h].push(profileForResponse(h, name, p));
        return json(res, 200, { profiles: result, active: activeForResponse(active), env_file: files.env });
      }
      if (req.method === 'POST' && url.pathname === '/api/profile') {
        const p = JSON.parse(await body(req)); const harness = p.harness; const name = String(p.name || '').trim();
        if (!harnesses[harness] || !name) return json(res, 400, { error: 'harness and name are required' });
        const profiles = readJson(files.profiles, {}); profiles[harness] ||= {}; const prior = profiles[harness][name] || {};
        const apiKey = p.api_key || decrypt(prior.api_key || {});
        profiles[harness][name] = { base_url: String(p.base_url || '').trim(), api_key: encrypt(apiKey), model: String(p.model || '').trim(), notes: String(p.notes || ''), updated_at: new Date().toISOString() };
        writeJson(files.profiles, profiles); return json(res, 200, { ok: true });
      }
      if (req.method === 'POST' && url.pathname === '/api/activate') {
        const p = JSON.parse(await body(req)); const profiles = readJson(files.profiles, {}); const stored = profiles[p.harness]?.[p.name];
        if (!harnesses[p.harness] || !stored) return json(res, 404, { error: 'profile not found' });
        const active = readJson(files.active, {}); const profile = { name: p.name, base_url: stored.base_url || '', api_key: decrypt(stored.api_key || {}), model: stored.model || '' };
        active[p.harness] = profile; writeJson(files.active, active); writeNativeConfig(p.harness, profile); writeEnv(active);
        return json(res, 200, { ok: true, env_file: files.env });
      }
      if (req.method === 'DELETE' && url.pathname.startsWith('/api/profile/')) {
        const [, , , harness, ...parts] = url.pathname.split('/'); const name = decodeURIComponent(parts.join('/')); const profiles = readJson(files.profiles, {});
        if (profiles[harness]?.[name]) { delete profiles[harness][name]; writeJson(files.profiles, profiles); }
        return json(res, 200, { ok: true });
      }
      return json(res, 404, { error: 'not found' });
    }
    return send(res, 404, 'Not found');
  } catch (err) { console.error(err); return json(res, 500, { error: 'internal server error' }); }
});

server.listen(PORT, HOST, () => {
  getPassword(); initSecret(files.key, 32);
  console.log(`[harness-switch] data directory: ${DATA_DIR}`);
  console.log(`[harness-switch] listening on http://${HOST}:${PORT}`);
});
